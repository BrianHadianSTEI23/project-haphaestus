"""Single source of truth for the active dataset version and location.

Every research script must resolve its dataset paths through this module so that
a regenerated corpus cannot silently be mixed with a stale one.  The dataset
metadata records ``generator_code_sha256``: a hash of all simulator and
task-generation source files.  ``verify_dataset.py`` refuses a split whose
recorded hash differs from the current source tree (the failure mode found in
the 2026-11-07 audit, where ``splits_v2`` had been generated by code that was
edited afterwards).

Override the location with ``HEPHAESTUS_SPLITS_DIR`` if needed.
"""
from __future__ import annotations

import hashlib
import os
from pathlib import Path

WM_ROOT = Path(__file__).resolve().parents[2]          # world_models_fpga/
DATASET_VERSION = "3.0.0-physical-counterfactuals"
LEGACY_VERSIONS = ("2.0.0-physical-counterfactuals",)
SPLITS_DIR = Path(os.environ.get("HEPHAESTUS_SPLITS_DIR", WM_ROOT / "research/datasets/splits_v3"))
# Checkpoints trained on SPLITS_DIR.  checkpoints/ (legacy, leaky data) and
# checkpoints_v2/ (trained on stale splits_v2) are preserved for history only.
CKPT_DIR = Path(os.environ.get("HEPHAESTUS_CKPT_DIR", WM_ROOT / "checkpoints_v3"))

# Files whose behaviour determines rendered observations, physics, labels and splits.
GENERATOR_SOURCES = (
    "env/amr_env.py",
    "env/amr_arena.xml",
    "research/datasets/generation/capability_tasks.py",
    "research/datasets/generation/expert_navigator.py",
    "research/datasets/generation/generate_benchmark_dataset.py",
    "research/datasets/counterfactual/counterfactual_generator.py",
    "research/datasets/counterfactual/disambiguation_tasks.py",
)


def split_path(name: str) -> Path:
    """Path of ``<name>.npz`` in the active split directory."""
    return SPLITS_DIR / f"{name}.npz"


def metadata_path(name: str) -> Path:
    return SPLITS_DIR / f"{name}_metadata.json"


def generator_code_sha256() -> str:
    """Deterministic hash over generator source files (path + content)."""
    h = hashlib.sha256()
    for rel in GENERATOR_SOURCES:
        p = WM_ROOT / rel
        h.update(rel.encode())
        h.update(p.read_bytes() if p.exists() else b"<missing>")
    return h.hexdigest()
